// Verifica "Importar planilla" (Admin → Clientes, parte 2.3) contra los emuladores con la demo cargada.
// Uso: node scripts/verify-importar.cjs http://127.0.0.1:5173 <carpeta> <planilla.xlsx>
const { chromium } = require('playwright');
const path = require('path');
const URL = process.argv[2] || 'http://127.0.0.1:5173';
const OUT = path.resolve(process.argv[3] || '.');
const FILE = process.argv[4];
require('fs').mkdirSync(OUT, { recursive: true });
const results = [];
const check = (name, ok, detail) => { results.push(ok); console.log(`${ok ? 'OK  ' : 'FALLA'} ${name}${detail ? ' · ' + detail : ''}`); };
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 1280, height: 1000 }, deviceScaleFactor: 2, locale: 'es-UY', timezoneId: 'America/Montevideo' });
  const p = await c.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(URL);
  await p.waitForSelector('text=/Probá la demo|Entrá a tu club/', { timeout: 40000 });
  await p.getByRole('button', { name: /Sofía Rodríguez/ }).click();
  await p.waitForTimeout(6000);
  await p.goto(`${URL}/?tab=admin`); await p.waitForTimeout(5000);
  await p.getByRole('button', { name: /^Clientes/ }).locator('visible=true').first().click();
  await p.waitForTimeout(2000);
  const before = Number((await p.getByTestId('clientes-lista').innerText()).match(/(\d+)\s*clientes/)?.[1] ?? 0);
  await p.getByRole('button', { name: 'Importar planilla' }).click();
  await p.waitForSelector('[data-testid=importar-planilla]');
  await p.screenshot({ path: `${OUT}/1-subir.png` });
  if (FILE) await p.locator('input[type=file]').setInputFiles(FILE);
  else await p.getByRole('button', { name: 'Probar con la planilla de ejemplo' }).click();
  await p.waitForSelector('text=Jugadores encontrados');
  const txt = await p.getByTestId('importar-planilla').innerText();
  check('Lee la planilla y muestra los números', /Jugadores encontrados\s*29/.test(txt) && /Repetidos que juntamos\s*1/.test(txt) && /Para revisar a mano\s*2/.test(txt), txt.replace(/\n/g, ' | ').slice(0, 300));
  const btn = p.getByRole('button', { name: /^Cargar \d+ jugadores$/ });
  check('Sin tildar el permiso no deja cargar', await btn.isDisabled());
  await p.screenshot({ path: `${OUT}/2-revisar.png`, fullPage: true });
  await p.getByRole('button', { name: /Ver los \d+ jugadores/ }).click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${OUT}/3-lista.png`, fullPage: true });
  await p.getByRole('checkbox').check();
  await btn.click();
  await p.waitForSelector('[data-testid=importar-listo]', { timeout: 60000 });
  await p.waitForTimeout(800);
  const done = await p.getByTestId('importar-listo').innerText();
  check('Carga y muestra el resultado', /29 fichas nuevas/.test(done) && /turnos fijos/.test(done), done.replace(/\n/g, ' | '));
  check('El resumen no cuenta como repetidas las fichas recién cargadas', !/Ya estaban en el club/.test(await p.getByTestId('importar-planilla').innerText()));
  await p.getByTestId('importar-listo').scrollIntoViewIfNeeded();
  await p.screenshot({ path: `${OUT}/4-listo.png` });
  await p.getByRole('button', { name: 'Ver clientes' }).click();
  await p.waitForTimeout(2000);
  const after = Number((await p.getByTestId('clientes-lista').innerText()).match(/(\d+)\s*clientes/)?.[1] ?? 0);
  check('La lista de clientes suma las fichas nuevas', after === before + 29, `${before} → ${after}`);
  await p.getByPlaceholder('Buscar por nombre, celular o mail').fill('Valentina Silva');
  await p.waitForTimeout(800);
  await p.screenshot({ path: `${OUT}/5-clientes.png` });
  check('Sin errores en la página', errs.length === 0, errs.join(' / '));
  await b.close();
  const bad = results.filter((x) => !x).length;
  console.log(`${results.length - bad} de ${results.length} bien`);
  process.exit(bad ? 1 : 0);
})().catch((e) => { console.error('FALLA', e.message); process.exit(1); });
