const { chromium } = require('playwright');
const OUT = '/tmp/claude-0/s/hueco';
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-UY', timezoneId: 'America/Montevideo' });
  const p = await c.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://127.0.0.1:5173');
  await p.waitForSelector('text=/Probá la demo|Entrá a tu club/', { timeout: 40000 });
  await p.getByRole('button', { name: /Diego Fernández/ }).click();
  await p.waitForTimeout(7000);
  await p.getByRole('button', { name: /^Mar/ }).first().click(); await p.waitForTimeout(1500);
  const free = p.getByRole('button', { name: /Cargar reserva/ }).locator('visible=true');
  console.log('libres', await free.count());
  await free.nth(6).click(); await p.waitForTimeout(500);
  await p.waitForSelector('[data-testid=hueco-vista-previa]', { timeout: 20000 });
  await p.getByRole('button', { name: /^Mixto/ }).click();
  await p.getByRole('button', { name: '−20 %' }).click();
  await p.screenshot({ path: OUT + '/1-vista-previa.png' });
  console.log((await p.locator('[data-testid=hueco-vista-previa]').innerText()).replace(/\n/g,' | '));
  await p.getByRole('button', { name: 'Llenar con la app', exact: true }).last().click();
  await p.waitForSelector('[data-testid=hueco-llenando]', { timeout: 30000 }); await p.waitForTimeout(2000);
  await p.screenshot({ path: OUT + '/2-llenando.png' });
  console.log((await p.locator('[data-testid=hueco-llenando]').innerText()).replace(/\n/g,' | '));
  await p.getByRole('button', { name: /Demo: que contesten/ }).click();
  await p.waitForSelector('text=¡Turno lleno!', { timeout: 40000 }); await p.waitForTimeout(1500);
  await p.screenshot({ path: OUT + '/3-lleno.png' });
  console.log((await p.locator('[data-testid=hueco-llenando]').innerText()).replace(/\n/g,' | '));
  await p.getByRole('button', { name: 'Listo' }).click(); await p.waitForTimeout(1500);
  await p.screenshot({ path: OUT + '/4-grilla.png', fullPage: false });
  console.log('errores', errs);
  await b.close();
})().catch((e) => { console.error('FALLA', e.message); process.exit(1); });
